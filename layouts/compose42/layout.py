"""
Compose42: the Corne key layout (crkbd, by foostan, CC BY 4.0; see NOTICE.md), as the left half in its local
frame, plus where the case hardware goes. Only the layout is used: everything else is generated by the
compose platform.

The key positions are the Corne's own: the switch cutouts of its 3x6 MX plate (plates/3x6/pcb/plate-top-cherrymx).
"""
from compose import params as PR
from compose.layout import Key, Layout, key_point


def layout():
    P = PR.KEY_PITCH
    M = PR.PLATE_MARGIN
    stagger = [0.0, 0.0, 0.25, 0.375, 0.25, 0.125]     # pinky, pinky, ring, middle, index, inner
    left = [["Tab", "Ctrl", "Shift"], ["Q", "A", "Z"], ["W", "S", "X"],
            ["E", "D", "C"], ["R", "F", "V"], ["T", "G", "B"]]
    right = [["Bksp", "'", "Esc"], ["P", ";", "/"], ["O", "L", "."],
             ["I", "K", ","], ["U", "J", "M"], ["Y", "H", "N"]]
    keys = []
    for c in range(6):
        for r in range(3):
            keys.append(Key(c * P, (-r + stagger[c]) * P, row=r, col=c,
                            label_l=left[c][r], label_r=right[c][r]))
    inner = 5
    # thumb fan: (x, y) in mm from the top outer key's centre, rot, h; matrix row 3, columns 3-5 as on the Corne
    thumbs = [(66.674, -54.768, 0.0, 1.0, 3, "Gui", "Alt"), (87.489, -56.945, -11.94, 1.0, 4, "Lower", "Raise"),
              (109.331, -59.026, -23.88, 1.5, 5, "Space", "Enter")]
    for x, y, rot, h, col, ll, lr in thumbs:
        keys.append(Key(x, y, rot, 1.0, h, 3, col, ll, lr, grid=False, accent=h > 1.0))

    kk = {k.label_l: k for k in keys}
    # plate supports: on column boundaries c1|c2 and c3|c4, 3 mm above the centres of rows 0 and 2
    posts = []
    for c in (1, 3):
        for r in (0, 2):
            posts.append(((c + 0.5) * P, (-r + (stagger[c] + stagger[c + 1]) / 2) * P + 3.0))
    xo = -P / 2 - M + 12
    feet = [(xo, P / 2 + M - 12), (xo, -2.5 * P - M + 12),
            key_point(kk["Lower"], 0.0, -(0.5 * P + M - 12))]
    # half-board art: the title in the top-left margin, the tagline up the outer edge (the board has no band wide
    # enough for it across), the build labels in the top-right margin, the board id in the top margin
    art = dict(title=(8.0, 11.0), tagline=(-11.0, -20.0, 90), labels=(96.0, 13.0), board_id=(57.0, 17.5))
    return Layout("corne", keys, inner, stagger[inner], posts, feet, art)
