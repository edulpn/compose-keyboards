"""
Compose58: the Lily58 key layout (by kata0510, MIT; see NOTICE.md), as the left half in its local
frame, plus where the case hardware goes. Only the layout is used: everything else is generated by
the compose platform.
"""
from compose import params as PR
from compose.layout import Key, Layout, key_point


def layout():
    P = PR.KEY_PITCH
    M = PR.PLATE_MARGIN
    stagger = [0.0, 0.0, 0.25, 0.375, 0.25, 0.125]     # pinky, pinky, ring, middle, index, inner
    left = [["Esc", "Tab", "Ctrl", "Shift"], ["1", "Q", "A", "Z"], ["2", "W", "S", "X"],
            ["3", "E", "D", "C"], ["4", "R", "F", "V"], ["5", "T", "G", "B"]]
    right = [["`", "-", "'", "Shift"], ["0", "P", ";", "/"], ["9", "O", "L", "."],
             ["8", "I", "K", ","], ["7", "U", "J", "M"], ["6", "Y", "H", "N"]]
    keys = []
    for c in range(6):
        for r in range(4):
            keys.append(Key(c * P, (-r + stagger[c]) * P, row=r, col=c,
                            label_l=left[c][r], label_r=right[c][r]))
    inner = 5
    # thumb arc: (dx from inner column, y, rot, h) in units; matrix col directly above
    thumbs = [(-3.0, -3.98, 0.0, 1.0, 2, "Alt", "Gui"), (-1.95, -4.02, -4.0, 1.0, 3, "Gui", "Bksp"),
              (-0.9, -4.12, -10.0, 1.0, 4, "Lower", "Raise"), (0.22, -4.55, -22.0, 1.5, 5, "Space", "Enter")]
    for dx, y, rot, h, col, ll, lr in thumbs:
        keys.append(Key((inner + dx) * P, y * P, rot, 1.0, h, 4, col, ll, lr))
    keys.append(Key((inner + 1.0) * P, -3.35 * P, 0.0, 1.0, 1.0, 4, 1, "[", "]"))   # extra inner key

    kk = {k.label_l: k for k in keys}
    s = PR.SCREW_EDGE_INSET
    x_out = -P / 2 - M + s
    ax = inner * P + P / 2 + M
    ay = stagger[inner] * P + P / 2 + M
    screws = [
        (x_out, P / 2 + M - s),                                    # back outer
        (ax - s, ay - s),                                          # back inner
        (x_out, -1.5 * P),                                         # outer middle
        (x_out, -3.5 * P - M + s),                                 # front outer
        key_point(kk["Gui"], 0.5 * P, -(0.5 * P + M - s)),         # thumb row front
        key_point(kk["Space"], 0.5 * P + M - s, -0.45 * P),        # beside the 1.5u
        (kk["["].x + 0.5 * P + M - s, kk["["].y + 0.25 * P),       # beside the inner key
    ]
    # plate supports: on column boundaries c1|c2 and c3|c4, 3 mm above the
    # centres of rows 1 and 3 (clear of the row wires 12.5 mm above each key)
    posts = []
    for c in (1, 3):
        for r in (1, 3):
            posts.append(((c + 0.5) * P, (-r + (stagger[c] + stagger[c + 1]) / 2) * P + 3.0))
    xo = -P / 2 - M + 12
    feet = [(xo, P / 2 + M - 12), (xo, -3.5 * P - M + 12),
            key_point(kk["Lower"], 0.0, -(0.5 * P + M - 12))]
    bays = {"bay30": (130.22, -120.86, -48.0)}    # rev 2 thumb bay: from `pointer-checks --suggest-bay`
    return Layout("lily58", keys, inner, stagger[inner], screws, posts, feet, bays)
